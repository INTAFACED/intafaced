import { generateKeyPairSync, randomBytes } from 'node:crypto';
import { beforeAll, describe, expect, it } from 'vitest';
import { createEdgeContext } from '@intafaced/contracts';
import { configureChannelsPolicy, describeChannelsPolicy, pushPublicKeyOf } from './channels-policy.js';
import { isPushPublicKey, parsePushPublicKey, PUSH_PUBLIC_KEY_INVALID } from './push-public-key.js';

/**
 * HM-notifications-02: the channels policy read carries the push gateway's
 * PUBLIC application key, or null when it is unset. The gateway token never.
 * A set key must be an unpadded base64url uncompressed P-256 public key, or the
 * boot refuses. Keys here are generated by the test; the token is its own string.
 */

const pair = generateKeyPairSync('ec', { namedCurve: 'P-256' });
const jwk = pair.publicKey.export({ format: 'jwk' }) as { x: string; y: string };
const KEY = Buffer.concat([Buffer.from([0x04]), Buffer.from(jwk.x, 'base64url'), Buffer.from(jwk.y, 'base64url')]).toString('base64url');
const PRIVATE_D = (pair.privateKey.export({ format: 'jwk' }) as { d: string }).d;
const TOKEN = 'test-push-gateway-token-must-never-leak-0001';

describe('push public key shape', () => {
  it('accepts an unpadded base64url 65-byte 0x04 key', () => {
    expect(KEY).toHaveLength(87);
    expect(isPushPublicKey(KEY)).toBe(true);
    expect(parsePushPublicKey(KEY)).toBe(KEY);
  });

  it('refuses a 43-character private-key-shaped value (32 bytes)', () => {
    expect(PRIVATE_D).toHaveLength(43);
    expect(isPushPublicKey(PRIVATE_D)).toBe(false);
    expect(() => parsePushPublicKey(PRIVATE_D)).toThrow(PUSH_PUBLIC_KEY_INVALID);
  });

  it('refuses a compressed key, a wrong prefix, padding, +/ and a token', () => {
    const raw = Buffer.from(KEY, 'base64url');
    const compressed = Buffer.concat([Buffer.from([0x02]), raw.subarray(1, 33)]).toString('base64url');
    const wrongPrefix = Buffer.concat([Buffer.from([0x05]), raw.subarray(1)]).toString('base64url');
    const padded = Buffer.from(raw).toString('base64'); // standard base64 with '=' padding
    for (const bad of [compressed, wrongPrefix, padded, `${KEY}=`, `${KEY.slice(0, 85)}+/`, TOKEN, randomBytes(66).toString('base64url')]) {
      expect(isPushPublicKey(bad)).toBe(false);
    }
  });
});

describe('boot validation (env.ts schema)', () => {
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  let envSchema: any;
  const BASE = {
    DATABASE_URL: 'postgres://svc_notify:svc_notify@localhost:5432/intafaced_notify_test',
    DATABASE_POOL_MAX: '10',
    EDGE_PRINCIPAL_SECRET: 'e'.repeat(40),
    SERVICE_NAME: 'svc-notify',
    APP_ENV: 'test',
  };
  beforeAll(async () => {
    // env.ts parses process.env at import time, same as env.test.ts.
    Object.assign(process.env, { ...BASE, NOTIFY_PUSH_PUBLIC_KEY: '' });
    ({ envSchema } = await import('./env.js'));
  });
  const parse = (key: string) => envSchema.safeParse({ ...BASE, NOTIFY_PUSH_PUBLIC_KEY: key });
  const codes = (r: { error?: { issues: Array<{ message: string }> } }) => r.error?.issues.map((i) => i.message) ?? [];

  it('blank and whitespace boot as not configured', () => {
    for (const blank of ['', '   ']) {
      const r = parse(blank);
      expect(r.success).toBe(true);
      expect(r.data.NOTIFY_PUSH_PUBLIC_KEY).toBeUndefined();
    }
  });

  it('a valid key boots', () => {
    const r = parse(KEY);
    expect(r.success).toBe(true);
    expect(r.data.NOTIFY_PUSH_PUBLIC_KEY).toBe(KEY);
  });

  it('a 43-character private-key-shaped value refuses the boot with the typed code', () => {
    const r = parse(PRIVATE_D);
    expect(r.success).toBe(false);
    expect(codes(r)).toContain(PUSH_PUBLIC_KEY_INVALID);
  });

  it('a token pasted into the key refuses the boot', () => {
    const r = parse(TOKEN);
    expect(r.success).toBe(false);
    expect(codes(r)).toContain(PUSH_PUBLIC_KEY_INVALID);
  });
});

describe('channelsPolicy.pushPublicKey', () => {
  it('key unset -> null', () => {
    expect(describeChannelsPolicy({}).pushPublicKey).toBeNull();
    expect(pushPublicKeyOf({ NOTIFY_PUSH_PUBLIC_KEY: '   ' })).toBeNull();
    expect(pushPublicKeyOf({ NOTIFY_PUSH_PUBLIC_KEY: '' })).toBeNull();
  });

  it('key set -> returned; token never present in output', () => {
    const policy = describeChannelsPolicy({ NOTIFY_PUSH_PUBLIC_KEY: KEY, NOTIFY_PUSH_GATEWAY_TOKEN: TOKEN } as never);
    expect(policy.pushPublicKey).toBe(KEY);
    const wire = JSON.stringify(policy);
    expect(wire).not.toContain(TOKEN);
    expect(wire).not.toMatch(/NOTIFY_PUSH_GATEWAY_TOKEN|gatewayToken/i);
  });

  it('the public router read carries the configured key and never the token', async () => {
    configureChannelsPolicy({ NOTIFY_PUSH_PUBLIC_KEY: KEY, NOTIFY_PUSH_GATEWAY_TOKEN: TOKEN } as never);
    try {
      const { createNotifyRouter } = await import('./router.js');
      const edgeContext = createEdgeContext({ secret: 'notify-push-key-test-edge-secret-value', serviceName: 'svc-notify' });
      const anon = edgeContext({ headers: { 'x-intafaced-region': 'DE' }, id: 'req-anon-push-key' });
      const result = await createNotifyRouter({} as never)
        .createCaller(anon)
        .notify.channelsPolicy();
      expect(result.pushPublicKey).toBe(KEY);
      expect(JSON.stringify(result)).not.toContain(TOKEN);
    } finally {
      configureChannelsPolicy({});
    }
  });
});
