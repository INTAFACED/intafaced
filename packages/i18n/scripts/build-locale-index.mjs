#!/usr/bin/env node
/**
 * Builds `src/locale-files.generated.ts` from every `src/locales/<code>.json`.
 *
 * Adding a language is dropping a file here: `{ "meta": { "provenance": "human" | "machine", "reviewedAt": null | "YYYY-MM-DD" },
 * "messages": { "<key>": "<text>" } }`. The generated index is committed so a build needs no step beyond `tsc`; the package
 * test fails when the index is out of date, and `--check` here does the same from the command line.
 */
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const dir = join(here, '..', 'src', 'locales');
const out = join(here, '..', 'src', 'locale-files.generated.ts');

export function readLocaleFiles() {
  const files = {};
  for (const name of readdirSync(dir)
    .filter((entry) => entry.endsWith('.json'))
    .sort()) {
    const code = name.slice(0, -'.json'.length);
    const parsed = JSON.parse(readFileSync(join(dir, name), 'utf8'));
    files[code] = parsed;
  }
  return files;
}

async function render(files) {
  const body = `// Generated by scripts/build-locale-index.mjs from src/locales/*.json. Do not edit by hand.\nimport type { LocaleFile } from './locale-file.js';\n\nexport const LOCALE_FILES: Readonly<Record<string, LocaleFile>> = ${JSON.stringify(files, null, 2)};\n`;
  try {
    const prettier = await import('prettier');
    const config = (await prettier.resolveConfig(out)) ?? {};
    return await prettier.format(body, { ...config, filepath: out });
  } catch {
    return body;
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = await render(readLocaleFiles());
  if (process.argv.includes('--check')) {
    if (!existsSync(out) || readFileSync(out, 'utf8') !== text) {
      console.error('locale-files.generated.ts is out of date: run `node scripts/build-locale-index.mjs`');
      process.exit(1);
    }
  } else writeFileSync(out, text);
}
