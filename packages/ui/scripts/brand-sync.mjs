#!/usr/bin/env node
/**
 * The brand's one source is `packages/ui/brand/`: the owner's kit files (marks, wordmark, lockups, favicon, app and
 * notification icons, social image). Swapping the brand is replacing those files and running this script; nothing else
 * draws the brand.
 *
 * It does two things:
 *   1. writes `src/brand/geometry.generated.ts` (the mark's three optical drawings, the iris blade, the wordmark and
 *      both lockups' placements), read from the SVGs, which the `Brand*` components draw;
 *   2. copies every file in `brand/` into each app that serves it (`apps/<app>/public/brand/`, wherever that folder
 *      exists), so favicons, manifests, notification icons and `<img>` lockups come from the same files.
 *
 *   node packages/ui/scripts/brand-sync.mjs           write both
 *   node packages/ui/scripts/brand-sync.mjs --check   exit 1 and name every file that differs (the test runs this)
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const UI = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = join(UI, 'brand');
const APPS = resolve(UI, '../../apps');
const GEOMETRY = join(UI, 'src/brand/geometry.generated.ts');

function svg(name) {
  return readFileSync(join(SOURCE, name), 'utf8');
}
function viewBox(text, name) {
  const m = /viewBox="0 0 ([\d.]+) ([\d.]+)"/.exec(text);
  if (!m) throw new Error(`brand-sync: ${name} has no 0-based viewBox`);
  return { width: Number(m[1]), height: Number(m[2]) };
}
function onlyPath(text, name) {
  const all = [...text.matchAll(/<path[^>]*\sd="([^"]+)"/g)];
  if (all.length !== 1) throw new Error(`brand-sync: ${name} should hold exactly one path, has ${all.length}`);
  return all[0][1];
}
/** A lockup's groups, in order: `<g transform="translate(x y) scale(s)">` around one path. */
function placements(text, name) {
  const groups = [...text.matchAll(/<g transform="translate\(([-\d.]+) ([-\d.]+)\) scale\(([\d.]+)\)">\s*<path[^>]*\sd="([^"]+)"/g)];
  if (groups.length !== 2) throw new Error(`brand-sync: ${name} should place a mark and a wordmark, has ${groups.length} groups`);
  return groups.map((g) => ({ x: Number(g[1]), y: Number(g[2]), scale: Number(g[3]), d: g[4] }));
}
/** A lockup as the kit draws it: where the mark and the wordmark sit, and which mark drawing it uses. */
function lockup(text, name, marks, wordmark) {
  const [m, w] = placements(text, name);
  const drawing = Object.keys(marks).find((k) => marks[k] === m.d);
  if (!drawing) throw new Error(`brand-sync: ${name} embeds a mark that is none of mark, mark-small or mark-micro`);
  if (w.d !== wordmark) throw new Error(`brand-sync: ${name} embeds a wordmark other than wordmark.svg`);
  const at = ({ x, y, scale }) => ({ x, y, scale });
  return { ...viewBox(text, name), drawing, mark: at(m), wordmark: at(w) };
}
/** The iris turns one blade: the mark's first sub-path, moved so its pivot (second vertex, the outer one) is 0,0. */
function blade(d, name) {
  const first = /^M([^Z]+)Z/.exec(d.trim());
  if (!first) throw new Error(`brand-sync: ${name} has no closed first blade`);
  const points = first[1].split(/\s*L\s*/).map((p) => p.trim().split(/\s+/).map(Number));
  const [px, py] = points[1];
  const round = (n) => Math.round(n * 10) / 10;
  const moved = points.map(([x, y]) => `${round(x - px)} ${round(y - py)}`);
  return { d: `M${moved.join(' L')}Z`, pivotX: px, pivotY: py };
}

export async function geometrySource() {
  const mark = svg('mark.svg');
  const small = svg('mark-small.svg');
  const micro = svg('mark-micro.svg');
  const word = svg('wordmark.svg');
  const horizontal = svg('lockup-horizontal.svg');
  const topbar = svg('lockup-topbar.svg');
  const stacked = svg('lockup-stacked.svg');
  for (const [text, name] of [
    [mark, 'mark.svg'],
    [small, 'mark-small.svg'],
    [micro, 'mark-micro.svg'],
  ]) {
    const box = viewBox(text, name);
    if (box.width !== 1000 || box.height !== 1000) throw new Error(`brand-sync: ${name} must be 1000 x 1000`);
  }
  const marks = { master: onlyPath(mark, 'mark.svg'), small: onlyPath(small, 'mark-small.svg'), micro: onlyPath(micro, 'mark-micro.svg') };
  const wordmark = onlyPath(word, 'wordmark.svg');
  const data = {
    mark: marks,
    blade: { master: blade(marks.master, 'mark.svg'), small: blade(marks.small, 'mark-small.svg') },
    wordmark: { d: wordmark, ...viewBox(word, 'wordmark.svg') },
    horizontal: lockup(horizontal, 'lockup-horizontal.svg', marks, wordmark),
    topbar: lockup(topbar, 'lockup-topbar.svg', marks, wordmark),
    stacked: lockup(stacked, 'lockup-stacked.svg', marks, wordmark),
  };
  const source = [
    '// Generated by packages/ui/scripts/brand-sync.mjs from packages/ui/brand/*.svg. Do not edit: change the kit files and run it.',
    '',
    `export const BRAND_GEOMETRY = ${JSON.stringify(data, null, 2)} as const;`,
    '',
  ].join('\n');
  // Written as the repo's formatter would write it, so a format run never puts the file out of step.
  const prettier = await import('prettier');
  return prettier.format(source, { ...(await prettier.resolveConfig(GEOMETRY)), filepath: GEOMETRY });
}

/** Apps whose pages, manifest and workers link to /brand/ files: their copy must exist, not only match. */
const REQUIRED = ['customer'];

/** Every app folder that serves the brand's files: the required ones, and any other that has the folder. */
export function targets() {
  const found = readdirSync(APPS, { withFileTypes: true })
    .filter((e) => e.isDirectory() && existsSync(join(APPS, e.name, 'public/brand')))
    .map((e) => e.name);
  return [...new Set([...REQUIRED, ...found])].map((app) => join(APPS, app, 'public/brand'));
}

export async function sync({ check = false } = {}) {
  const drift = [];
  const write = (path, body) => {
    const now = existsSync(path) ? readFileSync(path) : null;
    if (now && Buffer.compare(now, Buffer.from(body)) === 0) return;
    drift.push(path);
    if (!check) {
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, body);
    }
  };
  write(GEOMETRY, await geometrySource());
  const files = readdirSync(SOURCE).filter((f) => !f.startsWith('.'));
  for (const target of targets()) {
    for (const file of files) write(join(target, file), readFileSync(join(SOURCE, file)));
    for (const extra of existsSync(target) ? readdirSync(target) : []) {
      if (files.includes(extra)) continue;
      drift.push(`${join(target, extra)} (not in the kit)`);
      if (!check) rmSync(join(target, extra));
    }
  }
  return drift;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  const drift = await sync({ check });
  if (check && drift.length) {
    console.error(
      `brand-sync: these differ from packages/ui/brand (run node packages/ui/scripts/brand-sync.mjs):\n  ${drift.join('\n  ')}`,
    );
    process.exit(1);
  }
  console.log(check ? 'brand-sync: in step' : `brand-sync: wrote ${drift.length} file(s)`);
}
