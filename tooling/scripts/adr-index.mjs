#!/usr/bin/env node
/**
 * Builds docs/adr/README.md (the ADR index) from the files in docs/adr.
 * No dependencies. The README is generated: edit an ADR, then run this.
 *
 *   node tooling/scripts/adr-index.mjs           write docs/adr/README.md
 *   node tooling/scripts/adr-index.mjs --check   exit 1 if the README is stale
 *
 * An ADR is a file named YYYY-MM-DD-slug.md. Its date is the filename date. Its
 * title is the first `# ` heading (a leading "ADR:" is dropped). Its status is
 * the first word of its first `**Status:**` line (or `| **Status** |` table
 * row): proposed, accepted or superseded. Anything else is an error, so a
 * status nobody can read cannot slip in.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

export const STATUSES = ['proposed', 'accepted', 'superseded'];
const ADR_FILE = /^(\d{4}-\d{2}-\d{2})-.+\.md$/;

/** Parse one ADR. Throws a plain-English Error naming the file. */
export function parseAdr(file, text) {
  const m = ADR_FILE.exec(file);
  if (!m) throw new Error(`${file}: name must start with YYYY-MM-DD-`);
  const heading = /^# (.+)$/m.exec(text);
  if (!heading) throw new Error(`${file}: no "# " title line`);
  const title = heading[1].replace(/^ADR\s*[:—–-]\s*/i, '').trim();
  const line = /^\*\*Status:\*\*\s*(.*)$/m.exec(text) ?? /^\|\s*\*\*Status\*\*\s*\|\s*([^|]*?)\s*\|/m.exec(text);
  if (!line) throw new Error(`${file}: no "**Status:**" line`);
  const status = line[1]
    .replace(/\*/g, '')
    .trim()
    .split(/[\s—–:.,;(]/)[0]
    .toLowerCase();
  if (!STATUSES.includes(status))
    throw new Error(`${file}: status must start with ${STATUSES.join(' / ')}, got "${line[1].trim().slice(0, 40)}"`);
  return { file, title, status, date: m[1] };
}

/** Every ADR in `dir`, newest first. Collects all problems before throwing. */
export function readAdrs(dir) {
  if (!existsSync(dir)) return [];
  const rows = [];
  const problems = [];
  for (const file of readdirSync(dir)
    .filter((f) => ADR_FILE.test(f))
    .sort()
    .reverse()) {
    try {
      rows.push(parseAdr(file, readFileSync(join(dir, file), 'utf8')));
    } catch (e) {
      problems.push(e.message);
    }
  }
  if (problems.length) throw new Error(problems.join('\n'));
  return rows;
}

export function renderIndex(rows) {
  const count = (s) => rows.filter((r) => r.status === s).length;
  const esc = (s) => s.replace(/\|/g, '\\|');
  return [
    '# Decision records (ADR index)',
    '',
    '<!-- GENERATED by tooling/scripts/adr-index.mjs from the files in this folder. Do not edit by hand. -->',
    '',
    'Each file here records one decision: what was decided, the options weighed, and why. Only **accepted** records bind.',
    'A **proposed** record is a draft, and a **superseded** record is history. To change a decision, write a new record',
    'from [`TEMPLATE.md`](TEMPLATE.md) that supersedes the old one. Rules in force today are listed in',
    '[`../POLICY-REGISTER.md`](../POLICY-REGISTER.md).',
    '',
    `${rows.length} records: ${count('accepted')} accepted, ${count('proposed')} proposed, ${count('superseded')} superseded.`,
    '',
    '| Decision | Status | Date | Link |',
    '| --- | --- | --- | --- |',
    ...rows.map((r) => `| ${esc(r.title)} | ${r.status} | ${r.date} | [${r.file}](${r.file}) |`),
    '',
  ].join('\n');
}

const HERE = dirname(fileURLToPath(import.meta.url));
const DEFAULT_DIR = join(HERE, '..', '..', 'docs', 'adr');

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const check = process.argv.includes('--check');
  try {
    const next = renderIndex(readAdrs(DEFAULT_DIR));
    const path = join(DEFAULT_DIR, 'README.md');
    if (check) {
      if (!existsSync(path) || readFileSync(path, 'utf8') !== next) {
        console.error('docs/adr/README.md is stale. Run: node tooling/scripts/adr-index.mjs');
        process.exit(1);
      }
      console.log('docs/adr/README.md is current');
    } else {
      writeFileSync(path, next);
      console.log(`wrote docs/adr/README.md (${next.split('\n').length - 1} lines)`);
    }
  } catch (e) {
    console.error(`ADR index failed:\n${e.message}`);
    process.exit(1);
  }
}
