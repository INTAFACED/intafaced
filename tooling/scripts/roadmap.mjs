function cell(line) {
  const parts = line.replace(/\|\s*$/, '').split('|');
  return parts.length >= 3 ? [parts[1].trim(), parts.slice(2).join('|').trim()] : null;
}

/** Every slice in one spec file. */
export function parseSpec(text, module, group, file) {
  const slices = [];
  let cur = null;
  for (const line of text.split('\n')) {
    const m = HEADING.exec(line.trimEnd());
    if (m) {
      cur = { id: m[1], title: m[2].trim(), module, group, file, fields: {} };
      slices.push(cur);
      continue;
    }
    if (!cur || !line.startsWith('| ') || line.startsWith('| |') || line.startsWith('|---')) continue;
    const kv = cell(line);
    if (kv && kv[0] && kv[0].length < 30) cur.fields[kv[0]] = kv[1];
  }
  return slices;
}

const SAME_GROUP = /\bslices?\s+(\d{1,3}(?:\s*(?:,|and|or|&)\s*\d{1,3})*)(?!\s*(?:is |are )?not (?:needed|required))/gi;
// "Slice xfer-07": a slice of the same module named without its module letters.
const SAME_MODULE = /\b[Ss]lices?\s+([a-z][a-z0-9]*(?:-[a-z0-9]+)*-\d+[a-z]?)\b(?!\s*(?:is |are )?not (?:needed|required))/g;

/** The ids a Depends cell names as things this slice needs. "Slice 03" means slice 03 of the same group. */
export function dependsOn(text, known, self) {
  const cut = text.search(REVERSE);
  const needs = cut === -1 ? text : text.slice(0, cut);
  const ids = [...needs.matchAll(SLICE_ID)].map((m) => m[1]);
  const prefix = self.replace(/-\d+[a-z]?$/, '');
  for (const m of needs.matchAll(SAME_GROUP)) {
    for (const n of m[1].match(/\d+/g)) ids.push(`${prefix}-${n.padStart(2, '0')}`);
  }
  for (const m of needs.matchAll(SAME_MODULE)) ids.push(`${self.split('-')[0]}-${m[1]}`);
  return [...new Set(ids)].filter((id) => known.has(id) && id !== self).sort();
}

const uniq = (re, text, pick) => [...new Set([...text.matchAll(re)].map(pick))];

/** The lane a slice is built in: its back-end service when it has one, else its app area. */
export function laneFor({ module, services, packages, areas, apps }) {
  const svc = services.filter((s) => s !== 'svc-ledger');
  if (svc.length) {
    const first = svc[0];
    if (first === 'svc-trade') return module === 'derivatives' ? 'svc-trade futures' : 'svc-trade spot';
    if (first === 'svc-pay') return module === 'wallet' ? 'svc-pay wallet' : 'svc-pay merchant';
    return first;
  }
  if (services.includes('svc-ledger') || packages.includes('ledger-client')) return 'ledger';
  if (areas.length) return areas[0];
  if (packages.includes('contracts') || packages.includes('events')) return 'contracts';
  if (apps.length) return `${apps[0]} shell`;
  return 'unplaced';
}

function journeysFor(module, group) {
  const out = [];
  for (const [name, keys] of Object.entries(JOURNEYS)) {
    if (keys.includes(`${module}/*`) || keys.includes(`${module}/${group}`)) out.push(name);
  }
  return out;
}

/** Read the Operation Zero folder and return the committed index. `overrides` (docs/roadmap/lane-overrides.json) places slices by hand. */
export function buildIndex(ozDir, overrides = existsSync(OVERRIDES) ? JSON.parse(readFileSync(OVERRIDES, 'utf8')).lanes : {}) {
  const files = [];
  const modulesDir = join(ozDir, 'modules');
  for (const module of readdirSync(modulesDir).sort()) {
    const specs = join(modulesDir, module, 'specs');
    if (!existsSync(specs)) continue;
    for (const name of readdirSync(specs).sort()) if (name.endsWith('.md')) files.push({ path: join(specs, name), module });
  }
  const merchant = join(ozDir, 'specs');
  if (existsSync(merchant)) {
    for (const name of readdirSync(merchant).sort())
      if (/^merchant-.*\.md$/.test(name)) files.push({ path: join(merchant, name), module: 'merchant' });
  }
  const raw = [];
  for (const { path, module } of files) {
    if (/REVIEW|FIXES/.test(basename(path))) continue;
    raw.push(...parseSpec(readFileSync(path, 'utf8'), module, basename(path, '.md'), relative(ozDir, path)));
  }
  const known = new Set(raw.map((s) => s.id));
  const seen = new Set();
  const slices = [];
  for (const s of raw) {
    if (seen.has(s.id)) continue;
    seen.add(s.id);
    const where = `${s.fields.Module ?? ''} ${s.fields.Split ?? ''} ${s.fields.Routes ?? ''}`;
    const services = uniq(SERVICE, where, (m) => m[1]);
    const packages = uniq(PACKAGE, where, (m) => m[1]);
    const areas = uniq(APP_AREA, where, (m) => `${m[1]}: ${m[2]}`);
    const apps = uniq(APP, where, (m) => m[1]);
    const outside = (s.fields.NotConnected ?? '').trim();
    slices.push({
      id: s.id,
      title: s.title,
      module: s.module,
      group: s.group,
      spec: s.file,
      lane: overrides[s.id] ?? laneFor({ module: s.module, services, packages, areas, apps }),
      touches: [...services, ...packages.map((p) => `packages/${p}`), ...areas],
      depends: dependsOn(s.fields.Depends ?? '', known, s.id),
      journeys: journeysFor(s.module, s.group),
      outside: outside && !/^none\b/i.test(outside) ? outside.slice(0, 160) : '',
      size: (s.fields.Size ?? '').slice(0, 1),
      families: uniq(FAMILY_ID, s.fields.IDs ?? '', (m) => m[1]).length,
    });
  }
  return untangle(slices);
}

/**
 * Two slices whose specs each say they need the other cannot both go first. The one that comes first keeps its
 * place: the earlier slice in the same spec, else the one with fewer dependencies, else the lower id. Its edge to
 * the other moves to `later`, so the builder knows the spec named it and refuses with a typed code where it is
 * reached. Longer loops are left alone and listed as "untangle first".
 */
export function untangle(slices) {
  const byId = new Map(slices.map((s) => [s.id, s]));
  const pos = new Map(slices.map((s, i) => [s.id, i]));
  const goesFirst = (a, b) => {
    const A = byId.get(a);
    const B = byId.get(b);
    if (A.spec === B.spec) return pos.get(a) < pos.get(b);
    if (A.depends.length !== B.depends.length) return A.depends.length < B.depends.length;
    return a < b;
  };
  return slices.map((s) => {
    const later = s.depends.filter((d) => byId.get(d)?.depends.includes(s.id) && goesFirst(s.id, d));
    return later.length ? { ...s, depends: s.depends.filter((d) => !later.includes(d)), later } : s;
  });
}

/** Strongly connected groups (Tarjan, iterative) and a dependency depth per slice. */
export function analyse(slices) {
  const deps = new Map(slices.map((s) => [s.id, s.depends]));
  let counter = 0;
  const index = new Map();
  const low = new Map();
  const stack = [];
  const onStack = new Set();
  const groups = [];
  for (const start of deps.keys()) {
    if (index.has(start)) continue;
    const work = [[start, 0]];
    while (work.length) {
      const frame = work[work.length - 1];
      const [v, i] = frame;
      if (i === 0) {
        index.set(v, counter);
        low.set(v, counter++);
        stack.push(v);
        onStack.add(v);
      }
      const next = deps.get(v)[i];
      if (next !== undefined) {
        frame[1] = i + 1;
        if (!index.has(next)) work.push([next, 0]);
        else if (onStack.has(next)) low.set(v, Math.min(low.get(v), index.get(next)));
        continue;
      }
      work.pop();
      if (work.length) {
        const parent = work[work.length - 1][0];
        low.set(parent, Math.min(low.get(parent), low.get(v)));
      }
      if (low.get(v) === index.get(v)) {
        const group = [];
        let w;
        do {
          w = stack.pop();
          onStack.delete(w);
          group.push(w);
        } while (w !== v);
        groups.push(group);
      }
    }
  }
  const groupOf = new Map();
  groups.forEach((g, i) => g.forEach((v) => groupOf.set(v, i)));
  const depthOfGroup = [];
  groups.forEach((g, i) => {
    let d = 0;
    for (const v of g) for (const w of deps.get(v)) if (groupOf.get(w) !== i) d = Math.max(d, depthOfGroup[groupOf.get(w)]);
    depthOfGroup[i] = d + 1;
  });
  const depth = new Map([...deps.keys()].map((v) => [v, depthOfGroup[groupOf.get(v)]]));
  const tangled = new Set(groups.filter((g) => g.length > 1).flat());
  return { depth, tangled };
}

function count(list, key) {
  const out = new Map();
  for (const item of list) out.set(key(item), (out.get(key(item)) ?? 0) + 1);
  return [...out.entries()].sort((a, b) => b[1] - a[1] || String(a[0]).localeCompare(String(b[0])));
}

function table(header, rows) {
  return [`| ${header.join(' | ')} |`, `| ${header.map(() => '---').join(' | ')} |`, ...rows.map((r) => `| ${r.join(' | ')} |`)].join('\n');
}

/** Order a queue: slices that need nothing first, then by dependency depth; slices in a loop after the rest of their depth. */
export function queue(slices, analysis) {
  const rank = (s) => (s.depends.length === 0 && !analysis.tangled.has(s.id) ? 0 : 1);
  const loop = (s) => (analysis.tangled.has(s.id) ? 1 : 0);
  return [...slices].sort(
    (a, b) =>
      rank(a) - rank(b) ||
      analysis.depth.get(a.id) - analysis.depth.get(b.id) ||
      loop(a) - loop(b) ||
      a.module.localeCompare(b.module) ||
      a.id.localeCompare(b.id),
  );
}

function queueLines(slices, analysis) {
  return queue(slices, analysis).map((s) => {
    const flags = [s.size || '?', `depth ${analysis.depth.get(s.id)}`];
    if (analysis.tangled.has(s.id)) flags.push('untangle first');
    if (s.outside) flags.push('refuses for an outside service');
    const needs = s.depends.length ? ` · needs ${s.depends.join(', ')}` : '';
    return `- \`${s.id}\` ${s.title} (${flags.join(', ')})${needs}`;
  });
}

/** The generated half of docs/ROADMAP.md. */
export function render(slices) {
  const a = analyse(slices);
  const ready = slices.filter((s) => s.depends.length === 0 && !a.tangled.has(s.id));
  const out = [];
  out.push(GENERATED_MARK, '', '## Generated: what is left, by module, lane and journey', '');
  out.push(
    `${slices.length} slices left in ${new Set(slices.map((s) => s.module)).size} modules. ` +
      `${ready.length} need no other slice. ${a.tangled.size} sit in a dependency loop that the lane untangles first. ` +
      `${slices.filter((s) => s.outside).length} end in a refusal that names an outside service (built, switched on later). ` +
      `Size: ${count(slices, (s) => s.size || '?')
        .map(([k, n]) => `${n} ${k}`)
        .join(', ')}.`,
    '',
  );
  out.push('### By module', '');
  out.push(
    table(
      ['Module', 'Slices', 'Need nothing', 'Refuse for an outside service', 'Large'],
      count(slices, (s) => s.module).map(([m, n]) => {
        const own = slices.filter((s) => s.module === m);
        return [
          m,
          n,
          own.filter((s) => ready.includes(s)).length,
          own.filter((s) => s.outside).length,
          own.filter((s) => s.size === 'L').length,
        ];
      }),
    ),
    '',
  );
  out.push(
    '### By lane',
    '',
    'A lane is one service, or one app area, so two lanes never edit the same files. `--lane "<name>"` prints its queue.',
    '',
  );
  out.push(
    table(
      ['Lane', 'Slices', 'Need nothing', 'In the trader journey'],
      count(slices, (s) => s.lane).map(([l, n]) => {
        const own = slices.filter((s) => s.lane === l);
        return [l, n, own.filter((s) => ready.includes(s)).length, own.filter((s) => s.journeys.includes('trader')).length];
      }),
    ),
    '',
  );
  out.push('### By journey', '');
  out.push(
    table(
      ['Journey', 'Slices', 'Need nothing'],
      Object.keys(JOURNEYS).map((j) => {
        const own = slices.filter((s) => s.journeys.includes(j));
        return [j, own.length, own.filter((s) => ready.includes(s)).length];
      }),
    ),
    '',
  );
  out.push('### Trader journey queue', '', 'First milestone. Lanes take these before their other slices.', '');
  out.push(
    ...queueLines(
      slices.filter((s) => s.journeys.includes('trader')),
      a,
    ),
    '',
  );
  return out.join('\n');
}

/** The whole file in the repo's prettier format, so the format check never disagrees with --check. */
async function compose(slices) {
  const existing = existsSync(OUTPUT) ? readFileSync(OUTPUT, 'utf8') : '';
  const at = existing.indexOf(GENERATED_MARK);
  const plan = at === -1 ? existing : existing.slice(0, at);
  const prettier = await import('prettier');
  const config = (await prettier.resolveConfig(OUTPUT)) ?? {};
  return prettier.format(`${plan.trimEnd()}\n\n${render(slices)}`, { ...config, parser: 'markdown' });
}

/**
 * Progress from commit subjects on main. A merged PR whose title names a slice id counts toward that slice; reverts
 * do not count. Most slices take two or more PRs, so a named slice is started, not done: the slice's gap check on
 * main is the proof and is not automated yet. Rates are PRs and newly named slices per day, over the last 3 hours
 * (the live pace) and the last 7 days. `commits` is [{ at: ISO time, subject }], newest first; `now` is an ISO time.
 */
export function progress(slices, commits, now) {
  const known = new Set(slices.map((s) => s.id));
  const prs = new Map(); // slice id -> merge times, oldest last
  const sliceCommits = [];
  for (const { at, subject } of commits) {
    if (/^revert\b/i.test(subject)) continue;
    const ids = [...new Set([...subject.matchAll(SLICE_ID)].map((m) => m[1]).filter((id) => known.has(id)))];
    if (!ids.length) continue;
    sliceCommits.push(Date.parse(at));
    for (const id of ids) prs.set(id, [...(prs.get(id) ?? []), Date.parse(at)]);
  }
  const t = Date.parse(now);
  const HOUR = 3_600_000;
  const DAY = 24 * HOUR;
  const firstSeen = [...prs.values()].map((times) => Math.min(...times));
  // Inclusive start, so a window that begins at the first named merge counts that merge.
  const window = (ms) => ({
    prs: sliceCommits.filter((at) => at >= t - ms).length,
    started: firstSeen.filter((at) => at >= t - ms).length,
    days: ms / DAY,
  });
  const n = (count, word) => `${count} ${word}${count === 1 ? '' : 's'}`;
  const counts = [...prs.values()].map((times) => times.length);
  const perSlice = counts.length ? counts.reduce((a, b) => a + b, 0) / counts.length : 0;
  const left = slices.length - prs.size;
  const rate = ({ prs: count, started, days }) =>
    `${n(count, 'PR')}, ${n(started, 'slice')} started (${(count / days).toFixed(1)} PRs a day)`;
  const forecast = (label, w) => {
    const prsPerDay = w.prs / w.days;
    if (!prsPerDay) return `- Forecast at the ${label} pace: none (no slice PR merged in that window).`;
    const need = left * Math.max(perSlice, 2);
    const days = need / prsPerDay;
    return `- Forecast at the ${label} pace: about ${n(Math.ceil(days), 'day')} for the ${n(left, 'unstarted slice')} at ${Math.max(perSlice, 2).toFixed(1)} PRs each, about ${new Date(t + days * DAY).toISOString().slice(0, 10)}.`;
  };
  const h3 = window(3 * HOUR);
  // Before the first named merge nothing was tracked, so a 7-day window that reaches back past it would dilute the pace.
  const tracked = sliceCommits.length ? t - Math.min(...sliceCommits) : 7 * DAY;
  const d7 = window(Math.max(Math.min(7 * DAY, tracked), 3 * HOUR));
  const long = d7.days < 7 ? `${(d7.days * 24).toFixed(0)}-hour` : '7-day';
  const sameAsLive = d7.days * DAY <= 3 * HOUR;
  const lines = [
    `# Roadmap progress (${now.slice(0, 16).replace('T', ' ')} UTC)`,
    '',
    'Generated by `node tooling/scripts/roadmap.mjs --progress`. A merged PR whose title names a slice id counts toward that slice (reverts excluded). Most slices take two or more PRs, so "started" is not "done"; the gap check on main is not automated yet.',
    '',
    `- Started (named in at least one merged PR): ${prs.size} of ${slices.length} slices. Not started: ${left}.`,
    `- PRs per started slice: ${perSlice.toFixed(1)} on average; ${counts.filter((c) => c === 1).length} have one PR, ${counts.filter((c) => c === 2).length} two, ${counts.filter((c) => c > 2).length} three or more.`,
    `- Last 3 hours: ${rate(h3)}.`,
    ...(sameAsLive
      ? []
      : [`- Last ${d7.days < 7 ? `${(d7.days * 24).toFixed(0)} hours (since the first named merge)` : '7 days'}: ${rate(d7)}.`]),
    forecast('3-hour', h3),
    ...(sameAsLive ? [] : [forecast(long, d7)]),
    '',
    '| Lane | Slices | Started | PRs |',
    '| --- | --- | --- | --- |',
  ];
  const lanes = new Map();
  for (const s of slices) {
    const row = lanes.get(s.lane) ?? { all: 0, started: 0, prs: 0 };
    row.all++;
    if (prs.has(s.id)) {
      row.started++;
      row.prs += prs.get(s.id).length;
    }
    lanes.set(s.lane, row);
  }
  for (const [lane, r] of [...lanes].sort((a, b) => b[1].all - a[1].all)) lines.push(`| ${lane} | ${r.all} | ${r.started} | ${r.prs} |`);
  return `${lines.join('\n')}\n`;
}

async function main(argv) {
  const flag = (name) => {
    const i = argv.indexOf(name);
    return i === -1 ? undefined : (argv[i + 1] ?? '');
  };
  const ozDir = flag('--index');
  if (ozDir !== undefined) {
    if (!ozDir || !existsSync(join(ozDir, 'modules'))) {
      console.error('roadmap: --index needs the Operation Zero folder (it has modules/<module>/specs)');
      return 1;
    }
    const slices = buildIndex(ozDir);
    const prettier = await import('prettier');
    const config = (await prettier.resolveConfig(INDEX)) ?? {};
    writeFileSync(INDEX, await prettier.format(JSON.stringify(slices), { ...config, parser: 'json' }));
    console.log(`roadmap: ${slices.length} slices written to ${relative(ROOT, INDEX)}`);
    return 0;
  }
  const slices = JSON.parse(readFileSync(INDEX, 'utf8'));
  const ref = flag('--progress');
  if (ref !== undefined) {
    const log = execFileSync('git', ['log', ref || 'origin/main', '--since=120 days ago', '--format=%cI%x09%s'], {
      cwd: ROOT,
      encoding: 'utf8',
    });
    const commits = log
      .split('\n')
      .filter(Boolean)
      .map((line) => {
        const tab = line.indexOf('\t');
        return { at: line.slice(0, tab), subject: line.slice(tab + 1) };
      });
    console.log(progress(slices, commits, new Date().toISOString()));
    return 0;
  }
  const lane = flag('--lane');
  const journey = flag('--journey');
  if (lane !== undefined || journey !== undefined) {
    const pick = slices.filter((s) => (lane !== undefined ? s.lane === lane : s.journeys.includes(journey)));
    if (!pick.length) {
      console.error(`roadmap: nothing in ${lane !== undefined ? `lane "${lane}"` : `journey "${journey}"`}`);
      return 1;
    }
    console.log(queueLines(pick, analyse(slices)).join('\n'));
    return 0;
  }
  const next = await compose(slices);
  if (argv.includes('--check')) {
    const current = existsSync(OUTPUT) ? readFileSync(OUTPUT, 'utf8') : '';
    if (current !== next) {
      console.error('roadmap: docs/ROADMAP.md is stale; run `node tooling/scripts/roadmap.mjs`');
      return 1;
    }
    return 0;
  }
  writeFileSync(OUTPUT, next);
  console.log(`roadmap: wrote ${relative(ROOT, OUTPUT)}`);
  return 0;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) process.exit(await main(process.argv.slice(2)));
