#!/usr/bin/env node
/**
 * ROADMAP. One map of what is left to build, built from the Operation Zero spec slices.
 *
 *   node tooling/scripts/roadmap.mjs --index <operation-zero dir>   rebuild docs/roadmap/slices.json from the specs
 *   node tooling/scripts/roadmap.mjs                                 write the generated half of docs/ROADMAP.md
 *   node tooling/scripts/roadmap.mjs --check                         exit 1 if docs/ROADMAP.md is stale
 *   node tooling/scripts/roadmap.mjs --lane "<lane>"                 print one lane's queue, deepest dependency last
 *   node tooling/scripts/roadmap.mjs --journey trader                print one journey's queue
 *   node tooling/scripts/roadmap.mjs --progress [git ref] [--results <playwright json>]
 *                                                                   print progress: journeys passing in the real app
 *                                                                   (from the real-app run's JSON report), then slices
 *   node tooling/scripts/roadmap.mjs --finish-line [--results <playwright json>]
 *                                                                   print every live journey in the order to build it:
 *                                                                   launch first, then the journeys marked later
 *
 * Why: the specs are written per module (21 modules, about 1,240 slices) but the work is done per lane (one
 * service or app area per PR, AGENTS.md) and judged per journey. Build threads were picking rows from their own
 * lists, so nothing showed how much was left or what a slice waits on. This turns the specs into lanes,
 * dependencies and journeys mechanically; nobody types the tables.
 *
 * Sources:
 *   0. `modules/<module>/acceptance/journeys.md`: the journey map, the executable definition of done (goal agreed
 *      2026-10-20). Each `## J-<module>-NN: <title>` journey has Persona, Tier and Order lines and a step table whose
 *      Slices cell names slice ids or NO-SLICE. `--index` writes it to docs/roadmap/journeys.json and gives each slice
 *      the lowest Order of the journeys that need it, so lane queues take the first usable journeys first. The
 *      real-app browser run names each test `J-<module>-NN #<step> ...`; a journey passes when all its steps pass.
 *      A `Later: custody` line marks a journey that works only while INTAFACED holds customer money (OWNER 226): it
 *      stays live and in "finished", ranks after every launch journey, and is never Order 1, the launch wedge
 *      (customer-first order, OWNER 223 (3)); `--index` refuses a list that breaks this (finishLineProblems).
 *      A step whose "The person does" cell starts `Later (OWNER 226):` is a later step (`"later": "custody"` on the
 *      step): the custodial branch of a launch journey. It stays live and in "finished", but the launch count skips it
 *      (project-state tooling/truth/finish-line.mjs), the finish line's open count leaves it out, and a slice only later
 *      steps need is queued with the later journeys. A cell that starts with "Later" in any other form is refused.
 *   1. `modules/<module>/specs/*.md` and `specs/merchant-*.md` in the Operation Zero folder: each `### <ID>. <title>`
 *      heading and its `| IDs |`, `| Module |`, `| Split |`, `| Depends |`, `| NotConnected |`, `| Size |` rows.
 *      The folder lives in the project's shared files, not in this repo, so `--index` is run by whoever has it and
 *      the result is committed as docs/roadmap/slices.json.
 *   2. docs/roadmap/slices.json: the committed index everything else reads. docs/roadmap/lane-overrides.json places
 *      slices whose spec names no service, or the wrong one; it is applied by `--index`.
 *   3. The hand-written plan at the top of docs/ROADMAP.md, above GENERATED_MARK. It is kept as written.
 *
 * "Depends" is prose. A slice id counts as a dependency only when it appears before words that point the other
 * way ("Blocks", "Unblocks", "feeds", ...). Slices that still depend on each other in a loop are listed as
 * "untangle first" rather than guessed at.
 */
