const HEADING = /^###\s+([A-Z][A-Za-z0-9]*(?:-[A-Za-z0-9]+)*-\d+[a-z]?)\.?\s+(.*)$/;
// A slice id as its heading writes it (HEADING): upper-case segments too (OPS-ORD-01), and one segment before the number
// (LOAN-03). That shape also fits the specs' requirement ids (TRD-0082, ORD-001) and runs on into a joined range
// ("CB-bots-02-CB-bots-19"), so every start yields its shortest and its longest candidate (zero-width, so they may overlap)
// and only the ids that are slice headings are kept: parseJourneys' `known`, dependsOn's and the PR subjects' known slices.
// An id may touch punctuation, `_` or a hyphen, never another letter or digit.
const SLICE_ID =
  /(?<![A-Za-z0-9])(?=([A-Z][A-Za-z0-9]*(?:-[A-Za-z0-9]+)*?-\d+[a-z]?)(?![A-Za-z0-9]))(?=([A-Z][A-Za-z0-9]*(?:-[A-Za-z0-9]+)*-\d+[a-z]?)(?![A-Za-z0-9]))/g;
/**
 * Every slice-id candidate in `text`: each start's shortest and longest, for callers that keep the known ones. With
 * `longest`, only each start's longest that no earlier candidate contains (one id per id-shaped run, as a plain match).
 */
export function sliceIdCandidates(text, { longest = false } = {}) {
  const found = [...String(text).matchAll(SLICE_ID)].map((m) => ({ at: m.index, short: m[1], long: m[2] }));
  if (!longest) return [...new Set(found.flatMap((f) => [f.short, f.long]))];
  const out = [];
  let end = -1;
  for (const f of found) {
    if (f.at < end) continue;
    out.push(f.long);
    end = f.at + f.long.length;
  }
  return [...new Set(out)];
}
