function cell(line) {
  const parts = line.replace(/\|\s*$/, '').split('|');
  return parts.length >= 3 ? [parts[1].trim(), parts.slice(2).join('|').trim()] : null;
}

/** Every slice in one spec file. */
export function parseSpec(text, module, group, file) {
  const slices = [];
  let cur = null;
  for (const line of text.split('\n')) {
    const m = HEADING.exec(line.trimEnd());
    if (m) {
      cur = { id: m[1], title: m[2].trim(), module, group, file, fields: {} };
      slices.push(cur);
      continue;
    }
    if (!cur || !line.startsWith('| ') || line.startsWith('| |') || line.startsWith('|---')) continue;
    const kv = cell(line);
    if (kv && kv[0] && kv[0].length < 30) cur.fields[kv[0]] = kv[1];
  }
  return slices;
}

const JOURNEY_HEADING = /^##\s+(J-[a-z0-9-]+-\d+):\s+(.*)$/;
const JOURNEY_FIELD = /^-\s+(Persona|Tier|Order|Deferred|Parked|Later):\s*(.*)$/;
const STEP_ROW = /^\|\s*(\d+)\s*\|/;

/** Every journey in one module's acceptance/journeys.md: its fields and, per step, the slice ids it needs. */
export function parseJourneys(text, module, known = null) {
  const journeys = [];
  let cur = null;
  for (const raw of text.split('\n')) {
    const line = raw.trimEnd();
    const h = JOURNEY_HEADING.exec(line);
    if (h) {
      cur = { id: h[1], title: h[2].trim(), module, persona: '', tier: '', order: 0, steps: [] };
      journeys.push(cur);
      continue;
    }
    if (!cur) continue;
    if (line.startsWith('## ')) {
      cur = null;
      continue;
    }
    const f = JOURNEY_FIELD.exec(line);
    if (f) {
      if (f[1] === 'Order') cur.order = Number.parseInt(f[2], 10) || 0;
      else if (f[1] === 'Deferred') {
        // Only "until <when>" defers, so a "Deferred: no" never drops a journey quietly.
        if (!/^until\b/i.test(f[2].trim()))
          throw new Error(`roadmap: ${cur.id} has "Deferred: ${f[2].trim()}"; write "Deferred: until <when>"`);
        cur.deferred = true;
      } else if (f[1] === 'Parked') {
        // Parked (owner decision 2026-11-06, OWNER 183): kept in the plan and visible, built later, not counted. Like
        // Deferred, only "until <when>" parks, so a "Parked: no" never drops a journey quietly.
        const until = /^until\s+(.+)$/i.exec(f[2].trim());
        if (!until) throw new Error(`roadmap: ${cur.id} has "Parked: ${f[2].trim()}"; write "Parked: until <when>"`);
        cur.parked = true;
        cur.parkedUntil = until[1];
      } else if (f[1] === 'Later') {
        // Later (OWNER 226): only "custody" is a reason, so a "Later: no" or a typo never moves a journey quietly.
        if (!/^custody\b/i.test(f[2].trim()))
          throw new Error(`roadmap: ${cur.id} has "Later: ${f[2].trim()}"; the only later reason is "Later: custody"`);
        cur.later = 'custody';
      } else cur[f[1].toLowerCase()] = f[2].trim();
      continue;
    }
    const row = STEP_ROW.exec(line);
    if (row) {
      const cells = line.split('|').map((c) => c.trim());
      const sliceCell = cells[4] ?? '';
      const does = cells[2] ?? '';
      const slices = known ? sliceIdCandidates(sliceCell).filter((id) => known.has(id)) : sliceIdCandidates(sliceCell, { longest: true });
      // An empty cell names nothing to build either, so it counts as a step no slice covers yet.
      const step = { n: Number(row[1]), slices, noSlice: /\bNO-SLICE\b/.test(sliceCell) || !slices.length };
      if (LATER_STEP.test(does)) step.later = 'custody';
      else if (/^later\b/i.test(does)) throw new Error(`roadmap: ${cur.id} #${row[1]} starts with "Later" but not "Later (OWNER 226):"`);
      if (/\bDEFERRED\b/.test(sliceCell)) step.deferred = true;
      if (/\bPARKED\b/.test(sliceCell)) {
        if (!/\bPARKED until\s+\S/.test(sliceCell)) throw new Error(`roadmap: ${cur.id} #${row[1]} says PARKED with no "until <when>"`);
        step.parked = true;
        // "PARKED until <when> (<why>; was <slice ids>)": keep "<when> (<why>)" for the page, without the slice ids.
        step.parkedUntil = /\bPARKED until\s+(.*)$/
          .exec(sliceCell)[1]
          .replace(/;\s*was\b[^)]*\)/, ')')
          .trim();
      }
      cur.steps.push(step);
    }
  }
  return journeys;
}

/** The journey map of every module that has one, in module order. */
export function buildJourneys(ozDir, known = new Set(specSlices(ozDir).map((s) => s.id))) {
  const modulesDir = join(ozDir, 'modules');
  const out = [];
  for (const module of readdirSync(modulesDir).sort()) {
    const file = join(modulesDir, module, 'acceptance', 'journeys.md');
    if (existsSync(file)) out.push(...parseJourneys(readFileSync(file, 'utf8'), module, known));
  }
  const seen = new Set();
  for (const j of out) {
    if (seen.has(j.id)) throw new Error(`roadmap: journey id ${j.id} is used twice`);
    seen.add(j.id);
  }
  const problems = finishLineProblems(out);
  if (problems.length) throw new Error(`roadmap: ${problems.join('; ')}`);
  return out;
}

/** The one reason a journey moves later (OWNER 226); the finish line ranks it after every launch journey. */
export const LATER_REASONS = ['custody'];
/** The Order a later journey takes in the slice order: after Orders 1 to 3, so lane queues reach it last. */
export const LATER_ORDER = 4;
export const isLater = (j) => LATER_REASONS.includes(j.later);
/** The one way a step is marked later, at the start of its "The person does" cell (OWNER 226; #1865 A4). */
export const LATER_STEP = /^Later \(OWNER 226\):/;
/** A later step: the custodial branch inside a launch journey. Live and in "finished", never in the launch count. */
export const isLaterStep = (st) => LATER_REASONS.includes(st.later);

/**
 * Why the finish line's order is wrong: a `later` that isn't a known reason, or a later journey at Order 1. Order 1 is
 * the launch wedge, what a self-custody active trader walks in the first week (customer-first order, OWNER 223 (3);
 * the factory plan of 8 Nov, R5 §2), so a journey that needs INTAFACED to hold customer money can't be in it.
 * Parked and deferred journeys are checked too: they come back with their Order.
 */
export function finishLineProblems(journeys) {
  const out = [];
  for (const j of journeys) {
    if (j?.later === undefined) continue;
    if (!LATER_REASONS.includes(j.later)) out.push(`${j.id} is later for ${JSON.stringify(j.later)}; the only later reason is "custody"`);
    else if (j.order === 1) out.push(`${j.id} is later (custody) at Order 1; Order 1 is the launch wedge, so give it Order 2 or 3`);
  }
  return out;
}

/**
 * Every live journey in the order to build it (the factory plan of 8 Nov, R5 §2 rules 1 to 5): launch journeys before
 * later ones; then by Order; within an Order, customer journeys before operator ones, then the journeys whose slices
 * the most other live launch journeys share (they unblock the most), then the fewest steps not yet passing (all of a
 * journey's steps when no real-app report is given), then id. Each entry is { j, rank, later, unblocks, open }.
 */
export function finishLine(journeys, passed = null) {
  const live = liveJourneys(journeys);
  const launch = live.filter((j) => !isLater(j));
  const users = new Map();
  for (const j of launch)
    for (const id of new Set(j.steps.flatMap((st) => st.slices))) {
      if (!users.has(id)) users.set(id, new Set());
      users.get(id).add(j.id);
    }
  const unblocks = (j) => {
    const others = new Set();
    for (const id of new Set(j.steps.flatMap((st) => st.slices))) for (const o of users.get(id) ?? []) if (o !== j.id) others.add(o);
    return others.size;
  };
  // A launch journey's later steps aren't its launch work, so they don't count as open.
  const open = (j) => j.steps.filter((st) => (isLater(j) || !isLaterStep(st)) && !passed?.has(`${j.id}#${st.n}`)).length;
  const operator = (j) => (String(j.persona).startsWith('operator') ? 1 : 0);
  return live
    .map((j) => ({ j, later: isLater(j), unblocks: unblocks(j), open: open(j) }))
    .sort(
      (a, b) =>
        a.later - b.later ||
        (a.j.order || 9) - (b.j.order || 9) ||
        operator(a.j) - operator(b.j) ||
        b.unblocks - a.unblocks ||
        a.open - b.open ||
        a.j.id.localeCompare(b.j.id),
    )
    .map((e, i) => ({ ...e, rank: i + 1 }));
}

function finishLineLines(entries, passed) {
  const lines = [];
  let section = null;
  for (const e of entries) {
    const head = e.later ? `Later (${e.j.later}, OWNER 226): built when the custodial layer is switched on` : `Launch, Order ${e.j.order}`;
    if (head !== section) {
      if (section) lines.push('');
      lines.push(`## ${head}`);
      section = head;
    }
    const steps = passed ? `${e.open} of ${e.j.steps.length} steps not passing` : `${e.j.steps.length} steps`;
    lines.push(`${e.rank}. ${e.j.id} ${e.j.title} (${steps}; shares slices with ${e.unblocks} launch journeys; ${e.j.persona})`);
  }
  return lines;
}

/**
 * The journeys still to build: a journey with a `Deferred:` line, and a step whose Slices cell says DEFERRED, leave the
 * count and the slice order. Most wait for launch prep (legal and compliance work, owner decision 2026-10-27); a few are
 * set aside by another owner decision, which their Slices cell names (J-agents-12 #2, OWNER 107). A journey with a
 * `Parked:` line, and a step whose Slices cell says PARKED, leave them too (OWNER 183, 6 Nov 2026): they stay in the
 * plan and on the page, and come back the moment the line or the word is removed. A slice a live step still names keeps
 * its place, so a capability another journey needs is never parked with it.
 */
export const isLiveJourney = (j) => !j.deferred && !j.parked;
export const isLiveStep = (st) => !st.deferred && !st.parked;
export function liveJourneys(journeys) {
  return journeys
    .filter(isLiveJourney)
    .map((j) => ({ ...j, steps: j.steps.filter(isLiveStep) }))
    .filter((j) => j.steps.length);
}

/**
 * What the owner parked (OWNER 183): `whole`, the journeys out of the count because of parking (a `Parked:` line, or
 * every step that isn't deferred parked one by one); `steps`, the parked steps of journeys still live; `stepCount`, the
 * steps that leave the count by parking. `untilOf(j)` is when a journey or its parked steps come back.
 */
export function parkedJourneys(journeys) {
  const liveIds = new Set(liveJourneys(journeys).map((j) => j.id));
  const whole = journeys.filter((j) => !j.deferred && !liveIds.has(j.id) && (j.parked || j.steps.some((st) => !st.deferred && st.parked)));
  const steps = journeys
    .filter((j) => liveIds.has(j.id))
    .flatMap((j) => j.steps.filter((st) => !st.deferred && st.parked).map((st) => ({ j, st })));
  const stepCount = whole.reduce((c, j) => c + j.steps.filter((st) => !st.deferred).length, 0) + steps.length;
  return { whole, steps, stepCount };
}
const untilOf = (j) =>
  j.parkedUntil ?? [...new Set(j.steps.filter((st) => st.parked && !st.deferred).map((st) => st.parkedUntil))].join('; ');

/** Each slice's lowest journey Order (1 is a module's first usable journey); 0 when no journey names it. */
export function journeyOrder(journeys) {
  const order = new Map();
  for (const j of liveJourneys(journeys)) {
    if (!j.order) continue;
    // A later journey (OWNER 226) ranks after every launch journey, so a slice only it needs is queued last.
    const o = isLater(j) ? LATER_ORDER : j.order;
    for (const step of j.steps) {
      // A later step's slices are queued like a later journey's, unless a launch step also needs them.
      const so = isLaterStep(step) ? LATER_ORDER : o;
      for (const id of step.slices) order.set(id, Math.min(order.get(id) ?? 9, so));
    }
  }
  return order;
}

const SAME_GROUP = /\bslices?\s+(\d{1,3}(?:\s*(?:,|and|or|&)\s*\d{1,3})*)(?!\s*(?:is |are )?not (?:needed|required))/gi;
// "Slice xfer-07": a slice of the same module named without its module letters.
const SAME_MODULE = /\b[Ss]lices?\s+([a-z][a-z0-9]*(?:-[a-z0-9]+)*-\d+[a-z]?)\b(?!\s*(?:is |are )?not (?:needed|required))/g;

/** The ids a Depends cell names as things this slice needs. "Slice 03" means slice 03 of the same group. */
export function dependsOn(text, known, self) {
  const cut = text.search(REVERSE);
  const needs = cut === -1 ? text : text.slice(0, cut);
  const ids = sliceIdCandidates(needs);
  const prefix = self.replace(/-\d+[a-z]?$/, '');
  for (const m of needs.matchAll(SAME_GROUP)) {
    for (const n of m[1].match(/\d+/g)) ids.push(`${prefix}-${n.padStart(2, '0')}`);
  }
  for (const m of needs.matchAll(SAME_MODULE)) ids.push(`${self.split('-')[0]}-${m[1]}`);
  return [...new Set(ids)].filter((id) => known.has(id) && id !== self).sort();
}

const uniq = (re, text, pick) => [...new Set([...text.matchAll(re)].map(pick))];

/** The lane a slice is built in: its back-end service when it has one, else its app area. */
export function laneFor({ module, services, packages, areas, apps }) {
  const svc = services.filter((s) => s !== 'svc-ledger');
  if (svc.length) {
    const first = svc[0];
    if (first === 'svc-trade') return module === 'derivatives' ? 'svc-trade futures' : 'svc-trade spot';
    if (first === 'svc-pay') return module === 'wallet' ? 'svc-pay wallet' : 'svc-pay merchant';
    return first;
  }
  if (services.includes('svc-ledger') || packages.includes('ledger-client')) return 'ledger';
  if (areas.length) return areas[0];
  if (packages.includes('contracts') || packages.includes('events')) return 'contracts';
  if (apps.length) return `${apps[0]} shell`;
  return 'unplaced';
}

function journeysFor(module, group) {
  const out = [];
  for (const [name, keys] of Object.entries(JOURNEYS)) {
    if (keys.includes(`${module}/*`) || keys.includes(`${module}/${group}`)) out.push(name);
  }
  return out;
}

/** Read the Operation Zero folder and return the committed index. `overrides` (docs/roadmap/lane-overrides.json) places slices by hand. */
/** Every slice heading in the Operation Zero specs, as parseSpec reads them, before duplicates are resolved. */
export function specSlices(ozDir) {
  const files = [];
  const modulesDir = join(ozDir, 'modules');
  for (const module of readdirSync(modulesDir).sort()) {
    const specs = join(modulesDir, module, 'specs');
    if (!existsSync(specs)) continue;
    for (const name of readdirSync(specs).sort()) if (name.endsWith('.md')) files.push({ path: join(specs, name), module });
  }
  const merchant = join(ozDir, 'specs');
  if (existsSync(merchant)) {
    for (const name of readdirSync(merchant).sort())
      if (/^merchant-.*\.md$/.test(name)) files.push({ path: join(merchant, name), module: 'merchant' });
  }
  const raw = [];
  for (const { path, module } of files) {
    if (/REVIEW|FIXES/.test(basename(path))) continue;
    raw.push(...parseSpec(readFileSync(path, 'utf8'), module, basename(path, '.md'), relative(ozDir, path)));
  }
  return raw;
}

export function buildIndex(
  ozDir,
  overrides = existsSync(OVERRIDES) ? JSON.parse(readFileSync(OVERRIDES, 'utf8')).lanes : {},
  journeys = buildJourneys(ozDir),
) {
  const raw = specSlices(ozDir);
  const known = new Set(raw.map((s) => s.id));
  const seen = new Map();
  const slices = [];
  const order = journeyOrder(journeys);
  for (const s of raw) {
    // Two specs giving one id to different slices would silently drop one of them; the spec id has to change.
    if (seen.has(s.id)) throw new Error(`roadmap: slice id ${s.id} is used in both ${seen.get(s.id)} and ${s.file}`);
    seen.set(s.id, s.file);
    const where = `${s.fields.Module ?? ''} ${s.fields.Split ?? ''} ${s.fields.Routes ?? ''}`;
    const services = uniq(SERVICE, where, (m) => m[1]);
    const packages = uniq(PACKAGE, where, (m) => m[1]);
    const areas = uniq(APP_AREA, where, (m) => `${m[1]}: ${m[2]}`);
    const apps = uniq(APP, where, (m) => m[1]);
    const outside = (s.fields.NotConnected ?? '').trim();
    slices.push({
      id: s.id,
      title: s.title,
      module: s.module,
      group: s.group,
      spec: s.file,
      lane: overrides[s.id] ?? laneFor({ module: s.module, services, packages, areas, apps }),
      touches: [...services, ...packages.map((p) => `packages/${p}`), ...areas],
      depends: dependsOn(s.fields.Depends ?? '', known, s.id),
      journeys: journeysFor(s.module, s.group),
      outside: outside && !/^none\b/i.test(outside) ? outside.slice(0, 160) : '',
      size: (s.fields.Size ?? '').slice(0, 1),
      families: uniq(FAMILY_ID, s.fields.IDs ?? '', (m) => m[1]).length,
      order: order.get(s.id) ?? 0,
    });
  }
  return keepParkedNeeds(untangle(slices), journeys);
}

/**
 * Keep what a live journey needs (OWNER 183: "any capability other journeys need stays"). A slice that only parked
 * steps name has no journey order, so it would sink to the end of its lane. Every slice a live step names is walked
 * down its dependencies, through any slice that isn't itself live; each parked-only slice reached is marked `keptFor`
 * (the slices that need it directly) and takes the lowest order of the live slices that reach it, if they have one.
 */
export function keepParkedNeeds(slices, journeys) {
  const live = new Set(liveJourneys(journeys).flatMap((j) => j.steps.flatMap((st) => st.slices)));
  const parkedOnly = new Set(
    journeys
      .filter((j) => !j.deferred)
      .flatMap((j) => j.steps.filter((st) => !st.deferred && (j.parked || st.parked)).flatMap((st) => st.slices))
      .filter((id) => !live.has(id)),
  );
  if (!parkedOnly.size) return slices;
  const byId = new Map(slices.map((s) => [s.id, s]));
  const keptFor = new Map();
  const order = new Map();
  for (const root of slices.filter((s) => live.has(s.id))) {
    const seen = new Set([root.id]);
    const work = [root];
    while (work.length) {
      const s = work.pop();
      for (const d of s.depends) {
        const dep = byId.get(d);
        if (!dep || live.has(d) || seen.has(d)) continue;
        seen.add(d);
        if (parkedOnly.has(d)) {
          if (!keptFor.has(d)) keptFor.set(d, new Set());
          keptFor.get(d).add(s.id);
          if (root.order) order.set(d, Math.min(order.get(d) ?? 9, root.order));
        }
        work.push(dep);
      }
    }
  }
  return slices.map((s) => (keptFor.has(s.id) ? { ...s, order: order.get(s.id) ?? s.order, keptFor: [...keptFor.get(s.id)].sort() } : s));
}

/**
 * Two slices whose specs each say they need the other cannot both go first. The one that comes first keeps its
 * place: the earlier slice in the same spec, else the one with fewer dependencies, else the lower id. Its edge to
 * the other moves to `later`, so the builder knows the spec named it and refuses with a typed code where it is
 * reached. Longer loops are left alone and listed as "untangle first".
 */
export function untangle(slices) {
  const byId = new Map(slices.map((s) => [s.id, s]));
  const pos = new Map(slices.map((s, i) => [s.id, i]));
  const goesFirst = (a, b) => {
    const A = byId.get(a);
    const B = byId.get(b);
    if (A.spec === B.spec) return pos.get(a) < pos.get(b);
    if (A.depends.length !== B.depends.length) return A.depends.length < B.depends.length;
    return a < b;
  };
  return slices.map((s) => {
    const later = s.depends.filter((d) => byId.get(d)?.depends.includes(s.id) && goesFirst(s.id, d));
    return later.length ? { ...s, depends: s.depends.filter((d) => !later.includes(d)), later } : s;
  });
}

/** Strongly connected groups (Tarjan, iterative) and a dependency depth per slice. */
export function analyse(slices) {
  const deps = new Map(slices.map((s) => [s.id, s.depends]));
  let counter = 0;
  const index = new Map();
  const low = new Map();
  const stack = [];
  const onStack = new Set();
  const groups = [];
  for (const start of deps.keys()) {
    if (index.has(start)) continue;
    const work = [[start, 0]];
    while (work.length) {
      const frame = work[work.length - 1];
      const [v, i] = frame;
      if (i === 0) {
        index.set(v, counter);
        low.set(v, counter++);
        stack.push(v);
        onStack.add(v);
      }
      const next = deps.get(v)[i];
      if (next !== undefined) {
        frame[1] = i + 1;
        if (!index.has(next)) work.push([next, 0]);
        else if (onStack.has(next)) low.set(v, Math.min(low.get(v), index.get(next)));
        continue;
      }
      work.pop();
      if (work.length) {
        const parent = work[work.length - 1][0];
        low.set(parent, Math.min(low.get(parent), low.get(v)));
      }
      if (low.get(v) === index.get(v)) {
        const group = [];
        let w;
        do {
          w = stack.pop();
          onStack.delete(w);
          group.push(w);
        } while (w !== v);
        groups.push(group);
      }
    }
  }
  const groupOf = new Map();
  groups.forEach((g, i) => g.forEach((v) => groupOf.set(v, i)));
  const depthOfGroup = [];
  groups.forEach((g, i) => {
    let d = 0;
    for (const v of g) for (const w of deps.get(v)) if (groupOf.get(w) !== i) d = Math.max(d, depthOfGroup[groupOf.get(w)]);
    depthOfGroup[i] = d + 1;
  });
  const depth = new Map([...deps.keys()].map((v) => [v, depthOfGroup[groupOf.get(v)]]));
  const tangled = new Set(groups.filter((g) => g.length > 1).flat());
  return { depth, tangled };
}

function count(list, key) {
  const out = new Map();
  for (const item of list) out.set(key(item), (out.get(key(item)) ?? 0) + 1);
  return [...out.entries()].sort((a, b) => b[1] - a[1] || String(a[0]).localeCompare(String(b[0])));
}

function table(header, rows) {
  return [`| ${header.join(' | ')} |`, `| ${header.map(() => '---').join(' | ')} |`, ...rows.map((r) => `| ${r.join(' | ')} |`)].join('\n');
}

/**
 * Order a queue: slices that need nothing first, then the lowest journey Order (a module's first usable journey
 * before the rest; no journey last), then by dependency depth; slices in a loop after the rest of their depth.
 */
export function queue(slices, analysis) {
  const rank = (s) => (s.depends.length === 0 && !analysis.tangled.has(s.id) ? 0 : 1);
  const loop = (s) => (analysis.tangled.has(s.id) ? 1 : 0);
  const order = (s) => s.order || 9;
  return [...slices].sort(
    (a, b) =>
      rank(a) - rank(b) ||
      order(a) - order(b) ||
      analysis.depth.get(a.id) - analysis.depth.get(b.id) ||
      loop(a) - loop(b) ||
      a.module.localeCompare(b.module) ||
      a.id.localeCompare(b.id),
  );
}

function queueLines(slices, analysis) {
  return queue(slices, analysis).map((s) => {
    const flags = [s.size || '?', `depth ${analysis.depth.get(s.id)}`];
    if (s.order) flags.push(`journey order ${s.order}`);
    if (analysis.tangled.has(s.id)) flags.push('untangle first');
    if (s.keptFor) flags.push(`only parked journeys name it; kept for ${s.keptFor.join(', ')}`);
    if (s.outside) flags.push('refuses for an outside service');
    const needs = s.depends.length ? ` · needs ${s.depends.join(', ')}` : '';
    return `- \`${s.id}\` ${s.title} (${flags.join(', ')})${needs}`;
  });
}

