/**
 * Journey steps that passed in a Playwright JSON report, as "J-<module>-NN#<step>". Test titles start "J-x-NN #n".
 * A step passes only when every test under every spec with its key ran and ended expected: Playwright marks a skipped
 * spec `ok`, a failing duplicate title must not hide behind a passing one, and a test that passed only on its retry
 * ("flaky", on main since JOURNEY_RETRIES) is not a pass (CI review on #7363, 1fbf031).
 */
export function passedSteps(report) {
  const seen = new Set();
  const failed = new Set();
  const walk = (suite) => {
    for (const spec of suite.specs ?? []) {
      const m = /^(J-[a-z0-9-]+-\d+)\s+#(\d+)\b/.exec(spec.title ?? '');
      if (!m) continue;
      const key = `${m[1]}#${Number(m[2])}`;
      seen.add(key);
      const tests = spec.tests ?? [];
      if (!tests.length || !tests.every((t) => t.status === 'expected')) failed.add(key);
    }
    for (const child of suite.suites ?? []) walk(child);
  };
  for (const suite of report.suites ?? []) walk(suite);
  return new Set([...seen].filter((key) => !failed.has(key)));
}

/**
 * Progress. The scoreboard is journeys passing in the real app: `passed` holds the steps the real-app browser run on
 * main passed (from its JSON report), or is null when no report was given. Under it, slices from commit subjects on main. A merged PR whose title names a slice id counts toward that slice; reverts
 * do not count. Most slices take two or more PRs, so a named slice is started, not done: the slice's gap check on
 * main is the proof and is not automated yet. Rates are PRs and newly named slices per day, over the last 3 hours
 * (the live pace) and the last 7 days. `commits` is [{ at: ISO time, subject }], newest first; `now` is an ISO time.
 */
export function progress(slices, commits, now, allJourneys = [], passed = null) {
  const journeys = liveJourneys(allJourneys);
  // Every journey and step out of the count is either parked (OWNER 183) or deferred, so the three figures add up.
  const parked = parkedJourneys(allJourneys);
  const parkedSteps = parked.stepCount;
  const deferredJourneys = allJourneys.length - journeys.length - parked.whole.length;
  const deferredSteps =
    allJourneys.reduce((c, j) => c + j.steps.length, 0) - journeys.reduce((c, j) => c + j.steps.length, 0) - parkedSteps;
  const known = new Set(slices.map((s) => s.id));
  const prs = new Map(); // slice id -> merge times, oldest last
  const sliceCommits = [];
  for (const { at, subject } of commits) {
    if (/^revert\b/i.test(subject)) continue;
    const ids = sliceIdCandidates(subject).filter((id) => known.has(id));
    if (!ids.length) continue;
    sliceCommits.push(Date.parse(at));
    for (const id of ids) prs.set(id, [...(prs.get(id) ?? []), Date.parse(at)]);
  }
  const t = Date.parse(now);
  const HOUR = 3_600_000;
  const DAY = 24 * HOUR;
  const firstSeen = [...prs.values()].map((times) => Math.min(...times));
  // Inclusive start, so a window that begins at the first named merge counts that merge.
  const window = (ms) => ({
    prs: sliceCommits.filter((at) => at >= t - ms).length,
    started: firstSeen.filter((at) => at >= t - ms).length,
    days: ms / DAY,
  });
  const n = (count, word) => `${count} ${word}${count === 1 ? '' : 's'}`;
  const counts = [...prs.values()].map((times) => times.length);
  const perSlice = counts.length ? counts.reduce((a, b) => a + b, 0) / counts.length : 0;
  const left = slices.length - prs.size;
  const rate = ({ prs: count, started, days }) =>
    `${n(count, 'PR')}, ${n(started, 'slice')} started (${(count / days).toFixed(1)} PRs a day)`;
  const forecast = (label, w) => {
    const prsPerDay = w.prs / w.days;
    if (!prsPerDay) return `- Forecast at the ${label} pace: none (no slice PR merged in that window).`;
    const need = left * Math.max(perSlice, 2);
    const days = need / prsPerDay;
    return `- Forecast at the ${label} pace: about ${n(Math.ceil(days), 'day')} for the ${n(left, 'unstarted slice')} at ${Math.max(perSlice, 2).toFixed(1)} PRs each, about ${new Date(t + days * DAY).toISOString().slice(0, 10)}.`;
  };
  const h3 = window(3 * HOUR);
  // Before the first named merge nothing was tracked, so a 7-day window that reaches back past it would dilute the pace.
  const tracked = sliceCommits.length ? t - Math.min(...sliceCommits) : 7 * DAY;
  const d7 = window(Math.max(Math.min(7 * DAY, tracked), 3 * HOUR));
  const long = d7.days < 7 ? `${(d7.days * 24).toFixed(0)}-hour` : '7-day';
  const sameAsLive = d7.days * DAY <= 3 * HOUR;
  const stepCount = journeys.reduce((c, j) => c + j.steps.length, 0);
  const passing = journeys.filter((j) => j.steps.length && j.steps.every((st) => passed?.has(`${j.id}#${st.n}`)));
  const ready = journeys.filter((j) => j.steps.every((st) => !st.noSlice && st.slices.every((id) => prs.has(id))));
  const journeyLines = journeys.length
    ? [
        '## Journeys (the scoreboard)',
        '',
        passed
          ? `- Passing in the real app on main: ${passing.length} of ${journeys.length} journeys (${journeys.reduce((c, j) => c + j.steps.filter((st) => passed.has(`${j.id}#${st.n}`)).length, 0)} of ${stepCount} steps). Order 1: ${passing.filter((j) => j.order === 1).length} of ${journeys.filter((j) => j.order === 1).length}.`
          : `- Passing in the real app on main: not measured (no report from the real-app run was given). ${journeys.length} journeys, ${stepCount} steps.`,
        `- Every slice started (ready to prove, builders' claim): ${ready.length} of ${journeys.length} journeys.`,
        ...(deferredSteps
          ? [
              `- Deferred (launch prep, or set aside by an owner decision) and not counted: ${n(deferredJourneys, 'journey')} and ${n(deferredSteps, 'step')}.`,
            ]
          : []),
        ...(parkedSteps
          ? [`- Parked by the owner (OWNER 183) and not counted: ${n(parked.whole.length, 'whole journey')} and ${n(parkedSteps, 'step')}.`]
          : []),
        '',
        '## Slices',
        '',
      ]
    : [];
  const lines = [
    `# Roadmap progress (${now.slice(0, 16).replace('T', ' ')} UTC)`,
    '',
    'Generated by `node tooling/scripts/roadmap.mjs --progress`. A journey counts once its browser test passes on the real stack built from main. A merged PR whose title names a slice id counts toward that slice (reverts excluded). Most slices take two or more PRs, so "started" is not "done".',
    '',
    ...journeyLines,
    `- Started (named in at least one merged PR): ${prs.size} of ${slices.length} slices. Not started: ${left}.`,
    `- PRs per started slice: ${perSlice.toFixed(1)} on average; ${counts.filter((c) => c === 1).length} have one PR, ${counts.filter((c) => c === 2).length} two, ${counts.filter((c) => c > 2).length} three or more.`,
    `- Last 3 hours: ${rate(h3)}.`,
    ...(sameAsLive
      ? []
      : [`- Last ${d7.days < 7 ? `${(d7.days * 24).toFixed(0)} hours (since the first named merge)` : '7 days'}: ${rate(d7)}.`]),
    forecast('3-hour', h3),
    ...(sameAsLive ? [] : [forecast(long, d7)]),
    '',
    '| Lane | Slices | Started | PRs |',
    '| --- | --- | --- | --- |',
  ];
  const lanes = new Map();
  for (const s of slices) {
    const row = lanes.get(s.lane) ?? { all: 0, started: 0, prs: 0 };
    row.all++;
    if (prs.has(s.id)) {
      row.started++;
      row.prs += prs.get(s.id).length;
    }
    lanes.set(s.lane, row);
  }
  for (const [lane, r] of [...lanes].sort((a, b) => b[1].all - a[1].all)) lines.push(`| ${lane} | ${r.all} | ${r.started} | ${r.prs} |`);
  return `${lines.join('\n')}\n`;
}

