const OVERRIDES = join(ROOT, 'docs', 'roadmap', 'lane-overrides.json');
export const GENERATED_MARK = '<!-- generated by tooling/scripts/roadmap.mjs: do not edit below this line -->';

const HEADING = /^###\s+([A-Z][A-Za-z0-9]*(?:-[A-Za-z0-9]+)*-\d+[a-z]?)\.?\s+(.*)$/;
const SLICE_ID = /([A-Z][A-Za-z0-9]*(?:-[a-z0-9]+)+-\d+[a-z]?)/g;
const FAMILY_ID = /`([a-z0-9-]+-\d{3})`/g;
const REVERSE =
  /\b(?:Un)?[Bb]locks?\b|\bblocking\b|\bunlocks\b|\bfeeds\b|\bneeded by\b|\bused by\b|\bdepends\)|\bdepends on this\b|\blater slices?\b/;
const SERVICE = /\bservices\/(svc-[a-z0-9-]+)/g;
const PACKAGE = /\bpackages\/([a-z0-9-]+)/g;
const APP_AREA = /\bapps\/(customer|admin)\/src\/(?:app\/)?(?:features|screens|pages|routes|components|lib)\/([a-zA-Z0-9_-]+)/g;
const APP = /\bapps\/(customer|admin)\b/g;

