#!/usr/bin/env node
/**
 * ARCHITECTURE MAP. Keeps docs/ARCHITECTURE.md's counts and tables true to the folders.
 *
 *   node tooling/ci/architecture-map.mjs          rewrite the generated count block of docs/ARCHITECTURE.md
 *   node tooling/ci/architecture-map.mjs --check  fail if that block is stale or a table drifted (CI's check is architecture-map.test.mjs, run by tooling-tests)
 *
 * The count block (between the `architecture-map` markers) is generated from `ls apps`,
 * `ls services` and `ls packages`. The Apps and Services tables stay hand-written words, but
 * must hold exactly one row per folder; every package the "Packages that matter" table names
 * must exist. A hand-kept count had drifted (24 packages for 29, no `svc-campaigns` row:
 * project-state#2338), so drift now fails the gate instead of waiting for a reader.
 */
import { existsSync, readdirSync, readFileSync, realpathSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const DOC = 'docs/ARCHITECTURE.md';
export const START = '<!-- architecture-map:start (generated by `node tooling/ci/architecture-map.mjs`; do not edit by hand) -->';
export const END = '<!-- architecture-map:end -->';

/** Folder names directly under `root/<area>`, sorted. */
export function foldersOf(root, area) {
  const dir = join(root, area);
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((n) => !n.startsWith('.') && statSync(join(dir, n)).isDirectory())
    .sort();
}

const list = (names) => names.map((n) => `\`${n}\``).join(', ');

/** The generated count block, markers included. */
export function renderBlock({ apps, services, packages }) {
  return [
    START,
    '',
    `Count check: ${apps.length} apps under \`apps/\` (${list(apps)}), ${services.length} services under \`services/\`, ${packages.length} packages under \`packages/\` (${list(packages)}). Which services run in compose, their ports and required env: [\`SERVICES.md\`](SERVICES.md), generated from the code.`,
    '',
    END,
  ].join('\n');
}

/** Rows of the first table under the `## <heading>` section: the folder each row's first cell names. */
export function tableRows(doc, heading, area) {
  const lines = doc.split('\n');
  const at = lines.findIndex((l) => l.trim() === `## ${heading}`);
  if (at < 0) return null;
  const rows = [];
  let inTable = false;
  for (const line of lines.slice(at + 1)) {
    if (line.startsWith('## ')) break;
    if (!line.startsWith('|')) {
      if (inTable) break;
      continue;
    }
    inTable = true;
    const first = line.split('|')[1]?.trim() ?? '';
    if (/^-+$/.test(first) || !first.includes('`')) continue;
    // `packages/a`, `b` names packages/a and packages/b; `svc-x` names services/svc-x.
    for (const m of first.matchAll(/`([^`]+)`/g)) {
      const name = m[1].startsWith(`${area}/`) ? m[1].slice(area.length + 1) : m[1];
      rows.push(name);
    }
  }
  return rows;
}

/** Every reason docs/ARCHITECTURE.md is out of date, empty when it is current. */
export function problems(doc, folders) {
  const out = [];
  const s = doc.indexOf(START);
  const e = doc.indexOf(END);
  if (s < 0 || e < s) out.push(`${DOC} has no generated count block (markers missing).`);
  else if (doc.slice(s, e + END.length) !== renderBlock(folders))
    out.push(`${DOC}'s count block is stale. Run \`node tooling/ci/architecture-map.mjs\` and commit the result.`);

  const exact = [
    ['Apps', 'apps', folders.apps],
    ['Services', 'services', folders.services],
  ];
  for (const [heading, area, have] of exact) {
    const rows = tableRows(doc, heading, area);
    if (!rows) {
      out.push(`${DOC} has no "## ${heading}" table.`);
      continue;
    }
    for (const n of have.filter((n) => !rows.includes(n)))
      out.push(`${DOC} "## ${heading}" has no row for \`${area}/${n}\`: add one saying what it owns.`);
    for (const n of rows.filter((n) => !have.includes(n)))
      out.push(`${DOC} "## ${heading}" has a row for \`${area}/${n}\`, which does not exist: remove it.`);
    for (const n of rows.filter((n, i) => rows.indexOf(n) !== i)) out.push(`${DOC} "## ${heading}" lists \`${area}/${n}\` twice.`);
  }
  const named = tableRows(doc, 'Packages that matter', 'packages') ?? [];
  for (const n of named.filter((n) => !folders.packages.includes(n)))
    out.push(`${DOC} "## Packages that matter" names \`packages/${n}\`, which does not exist: remove it.`);
  return out;
}

export function currentFolders(root = ROOT) {
  return {
    apps: foldersOf(root, 'apps'),
    services: foldersOf(root, 'services'),
    packages: foldersOf(root, 'packages'),
  };
}

if (process.argv[1] && realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url))) {
  const path = join(ROOT, DOC);
  const folders = currentFolders();
  if (!existsSync(path) || !folders.apps.length || !folders.services.length || !folders.packages.length) {
    console.error(`ARCHITECTURE MAP FAILED - ${DOC}, apps/, services/ or packages/ is missing or empty: nothing was checked.`);
    process.exit(1);
  }
  const doc = readFileSync(path, 'utf8');
  if (process.argv.includes('--check')) {
    const found = problems(doc, folders);
    if (found.length) {
      for (const p of found) console.error(p);
      process.exit(1);
    }
    console.log(`architecture map: ${DOC} is current`);
  } else {
    const s = doc.indexOf(START);
    const e = doc.indexOf(END);
    if (s < 0 || e < s) {
      console.error(`${DOC} has no architecture-map markers; add them where the count line belongs.`);
      process.exit(1);
    }
    writeFileSync(path, doc.slice(0, s) + renderBlock(folders) + doc.slice(e + END.length));
    console.log(`wrote ${DOC}'s count block`);
    const rest = problems(readFileSync(path, 'utf8'), folders);
    for (const p of rest) console.error(p);
    if (rest.length) process.exit(1);
  }
}
