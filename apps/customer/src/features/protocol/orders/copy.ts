/** The copy key for a refusal code that has its own words here, or null: any other code reads as a plain refusal. */
export function refusalKey(code: string): keyof typeof en | null {
  const key = `refused_${code.replace(/\./g, '_')}`;
  return Object.hasOwn(en, key) ? (key as keyof typeof en) : null;
}
