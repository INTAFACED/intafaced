// Only locally authored refusals are retranslated. Provider results retain their
// original message and wire shape; this metadata never enters the write journal.
type PayRefusal = Extract<ApiResult<never>, { ok: false }>;
const authoredRefusals = new WeakMap<PayRefusal, () => string>();
type PayArguments<K extends keyof typeof messages> = Parameters<typeof payCopy.t<K>> extends [unknown, ...infer A] ? A : never;
export function payRefusal<K extends keyof typeof messages>(
  key: K,
  options: { reason?: PayRefusal['reason']; code?: string },
  ...args: PayArguments<K>
): PayRefusal {
  // PayArguments is the existing translator tuple after its key argument.
  // TypeScript cannot recombine a generic conditional tuple at this boundary.
  const translate = payCopy.t as unknown as (key: K, ...args: PayArguments<K>) => string;
  const message = () => translate(key, ...args);
  const result: PayRefusal = {
    ok: false,
    reason: options.reason ?? 'forbidden',
    message: message(),
    ...(options.code ? { code: options.code } : {}),
  };
  authoredRefusals.set(result, message);
  return result;
}
export function payAuthoredMessage(result: PayRefusal): string | undefined {
  return authoredRefusals.get(result)?.();
}
