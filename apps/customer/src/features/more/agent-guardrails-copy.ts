/** Whether a key has words, so a tool the copy does not name shows by its own name instead of a missing message. */
type PlainKey = { [K in keyof typeof en]: (typeof en)[K] extends `${string}{${string}` ? never : K }[keyof typeof en];
export const hasGuardrailWords = (key: string): key is PlainKey => Object.hasOwn(en, key) && !en[key as keyof typeof en].includes('{');
