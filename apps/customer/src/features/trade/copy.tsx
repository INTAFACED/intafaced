/** Timestamp presentation follows View; source ISO values and candle boundaries
 * stay with their contracts. Invalid timestamps retain the native unknown text. */
export function tradeDate(value: string | number, style: 'date' | 'time' | 'dateTime' = 'dateTime') {
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return 'Invalid Date';
  const { language, timeZone } = currentPreferences();
  const options = timeZone === 'device' ? {} : { timeZone: timeZone === 'UTC+8' ? 'Etc/GMT-8' : 'UTC' };
  return style === 'date'
    ? date.toLocaleDateString(language, options)
    : style === 'time'
      ? date.toLocaleTimeString(language, options)
      : date.toLocaleString(language, options);
}

// Authored refusal provenance stays outside the API object and recovery marker.
// Original provider messages are never matched or translated.
type TradeRefusal = Extract<ApiResult<never>, { ok: false }>;
type TradeArguments<K extends keyof typeof en> = Parameters<typeof tradeCopy.t<K>> extends [unknown, ...infer A] ? A : never;
const authoredRefusals = new WeakMap<object, () => string>();
export function tradeRefusal<K extends keyof typeof en, const O extends { reason: string }>(
  key: K,
  options: O,
  ...args: TradeArguments<K> | [() => TradeArguments<K>]
): O & { ok: false; message: string } {
  const translate = tradeCopy.t as unknown as (key: K, ...args: TradeArguments<K>) => string;
  const message = () => translate(key, ...((typeof args[0] === 'function' ? args[0]() : args) as TradeArguments<K>));
  const result = { ok: false as const, ...options, message: message() };
  authoredRefusals.set(result, message);
  return result;
}
export function tradeError<K extends keyof typeof en>(key: K, ...args: TradeArguments<K>): Error {
  const translate = tradeCopy.t as unknown as (key: K, ...args: TradeArguments<K>) => string;
  const message = () => translate(key, ...args);
  const error = new Error(message());
  authoredRefusals.set(error, message);
  return error;
}
export function tradeFailureFrom(source: { message: string; messageCopy?: UiMessage }, reason: TradeRefusal['reason']): TradeRefusal {
  const result: TradeRefusal = { ok: false, reason, message: source.message };
  const message = authoredRefusals.get(source) ?? (source.messageCopy ? () => uiMessage(source.messageCopy!) : undefined);
  if (message) authoredRefusals.set(result, message);
  return result;
}
export function TradeOriginalMessage({ source }: { source: { message: string; messageCopy?: UiMessage } }) {
  const { requestedLocale } = tradeCopy.useCopy();
  const message = authoredRefusals.get(source);
  const sharedLanguage = source.messageCopy ? uiCopy.forLocale(requestedLocale).languageFor(source.messageCopy.key) : undefined;
  return (
    <span lang={message ? requestedLocale : (sharedLanguage ?? 'und')}>
      {message ? message() : source.messageCopy ? uiMessage(source.messageCopy, requestedLocale) : source.message}
    </span>
  );
}

/** Service prose has no supplied language. Explicit authored refusals follow
 * the current locale without changing the original API message or wire data. */
export function TradeFailure(props: Parameters<typeof Failure>[0]) {
  const { requestedLocale } = tradeCopy.useCopy();
  const message = authoredRefusals.get(props.result);
  return (
    <div lang={message ? requestedLocale : 'und'} style={{ display: 'contents' }}>
      <Failure {...props} result={message ? { ...props.result, message: message() } : props.result} />
    </div>
  );
}
