/** Whether a decline code has plain words. */
export const declineKey = (code: string): keyof typeof en | null => {
  const key = `decline_${code.replaceAll('.', '_')}`;
  return Object.hasOwn(en, key) ? (key as keyof typeof en) : null;
};
